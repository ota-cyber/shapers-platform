#!/usr/bin/env python3
"""Build supabase/seed.sql from the hackathon sandbox package in sandbox/.

Standard library only. The generated seed.sql is committed, so rebuilding the
database never needs Python; run this again only if the sandbox files change.

    python3 scripts/build_seed.py

Imported as-is: roster, weekly hours, attendance, meetings (.ics).
Invented for the demo (marked below): join dates, buddies, onboarding progress,
one pause, projects and tasks. The sandbox has no project or task data.
"""

import datetime as dt
import random
import re
import uuid
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SANDBOX = ROOT / "sandbox"
OUT = ROOT / "supabase" / "seed.sql"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
ID_NS = uuid.UUID("5b1c1f5e-7a52-4d0c-9a8e-3c0de5a9e001")
TODAY = dt.date(2026, 10, 24)  # hackathon day; keeps the demo data stable

SERIES_IDS = {
    "Community": "community",
    "Summer School": "summer-school",
    "Grants": "grants",
    "Shape Talks": "shape-talks",
    "Shapers Tech": "shapers-tech",
    "Shapers Voice": "shapers-voice",
}
TIERS = {"GO!": "go", "Impact": "impact", "Core": "core"}


def sid(*parts):
    return str(uuid.uuid5(ID_NS, "/".join(parts)))


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def read_xlsx(path):
    """First sheet as a list of dicts keyed by the header row."""
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
            shared.append("".join(t.text or "" for t in si.iter(f"{{{NS['m']}}}t")))
    rows = []
    for r in ET.fromstring(z.read("xl/worksheets/sheet1.xml")).iter(f"{{{NS['m']}}}row"):
        row = {}
        for c in r.findall("m:c", NS):
            col = re.match(r"[A-Z]+", c.get("r")).group()
            v, t = c.find("m:v", NS), c.get("t")
            if t == "inlineStr":
                val = "".join(x.text or "" for x in c.iter(f"{{{NS['m']}}}t"))
            elif v is None:
                val = None
            elif t == "s":
                val = shared[int(v.text)]
            else:
                val = v.text
            row[col] = val
        rows.append(row)
    cols = sorted({k for r in rows for k in r}, key=lambda s: (len(s), s))
    header = [rows[0].get(c) for c in cols]
    return [{h: r.get(c) for h, c in zip(header, cols)} for r in rows[1:]]


def excel_date(v):
    return dt.date(1899, 12, 30) + dt.timedelta(days=int(float(v)))


def read_ics(path):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    text = re.sub(r"\n[ \t]", "", text)  # unfold continuation lines
    events = []
    for block in re.findall(r"BEGIN:VEVENT\n(.*?)\nEND:VEVENT", text, re.S):
        ev = {}
        for line in block.split("\n"):
            key, _, val = line.partition(":")
            ev[key.split(";")[0]] = val.replace("\\n", "\n").replace("\\,", ",")
        events.append(ev)
    return events


def ics_time(v):
    return dt.datetime.strptime(v, "%Y%m%dT%H%M%SZ").replace(tzinfo=dt.timezone.utc)


def local_date(ts):
    # Europe/Ljubljana is UTC+2 until 2026-10-25, UTC+1 after; meetings are evenings.
    offset = 2 if ts < dt.datetime(2026, 10, 25, 1, tzinfo=dt.timezone.utc) else 1
    return (ts + dt.timedelta(hours=offset)).date()


def main():
    rnd = random.Random(42)
    out = ["-- Generated by scripts/build_seed.py. Do not edit by hand.", "begin;", ""]
    out.append("-- Sandbox hours start the week of 2026-09-14")
    out.append("update public.app_settings set tracking_since = '2026-09-14';")
    out.append("")

    # ------------------------------------------------------------ members (roster)
    roster = read_xlsx(SANDBOX / "roster.xlsx")
    members = []
    for r in roster:
        members.append({
            "id": sid("member", r["email"]),
            "name": r["name"],
            "email": r["email"],
            "tier": TIERS[r["tier"]],
            "admin": r["admin"] == "yes",
            "series": [s.strip() for s in r["series"].split(";")],
        })
    admins = [m for m in members if m["admin"]]

    # Invented: join dates. Four GO! members are this autumn's onboarding cohort.
    go = [m for m in members if m["tier"] == "go"]
    cohort = {m["email"] for m in go[-4:]}
    for i, m in enumerate(members):
        if m["tier"] == "core":
            m["joined"] = dt.date(2023, 10, 1) + dt.timedelta(days=90 * i)
            m["tier_since"] = m["joined"] + dt.timedelta(days=365)
        elif m["tier"] == "impact":
            m["joined"] = dt.date(2024, 10, 1) + dt.timedelta(days=45 * i)
            m["tier_since"] = m["joined"] + dt.timedelta(days=183)
        elif m["email"] in cohort:
            m["joined"] = dt.date(2026, 9, 14)
            m["tier_since"] = m["joined"]
        else:
            m["joined"] = dt.date(2026, 3, 2) + dt.timedelta(days=21 * (i % 6))
            m["tier_since"] = m["joined"]
        m["buddy"] = None
    # Invented: buddies (today the leaders are the buddies).
    for i, m in enumerate([m for m in go]):
        m["buddy"] = admins[i % len(admins)]["id"]

    out.append("-- Members (sandbox roster; join dates and buddies invented for the demo)")
    out.append("insert into public.members (id, name, email, tier, is_admin, joined_on, tier_since) values")
    out.append(",\n".join(
        f"  ({q(m['id'])}, {q(m['name'])}, {q(m['email'])}, {q(m['tier'])}, {q(m['admin'])}, "
        f"{q(m['joined'].isoformat())}, {q(m['tier_since'].isoformat())})" for m in members) + ";")
    out.append("")
    for m in members:
        if m["buddy"]:
            out.append(f"update public.members set buddy_id = {q(m['buddy'])} where id = {q(m['id'])};")
    out.append("")

    out.append("insert into public.series_members (series_id, member_id) values")
    pairs = [(SERIES_IDS[s], m["id"]) for m in members for s in m["series"] if s != "Community"]
    out.append(",\n".join(f"  ({q(s)}, {q(mid)})" for s, mid in pairs) + ";")
    out.append("")

    # ------------------------------------------------------------ meetings (.ics)
    events = read_ics(SANDBOX / "meetings.ics")
    meetings = {}
    out.append("-- Meetings (sandbox meetings.ics; the Calendar sync updates the same rows by iCal UID)")
    out.append("insert into public.meetings (id, ical_uid, series_id, title, starts_at, ends_at, location, description) values")
    rows = []
    for ev in events:
        series = re.search(r"Series: (.+)", ev["DESCRIPTION"]).group(1).strip()
        start, end = ics_time(ev["DTSTART"]), ics_time(ev["DTEND"])
        mid = sid("meeting", ev["UID"])
        meetings[(SERIES_IDS[series], local_date(start))] = (mid, start)
        rows.append(f"  ({q(mid)}, {q(ev['UID'])}, {q(SERIES_IDS[series])}, {q(ev['SUMMARY'])}, "
                    f"{q(start.isoformat())}, {q(end.isoformat())}, {q(ev.get('LOCATION'))}, {q(ev['DESCRIPTION'])})")
    out.append(",\n".join(rows) + ";")
    out.append("")

    # ------------------------------------------------------------ attendance (import)
    by_email = {m["email"]: m for m in members}
    att_rows, missing = [], 0
    for r in read_xlsx(SANDBOX / "attendance-flat.xlsx"):
        key = (SERIES_IDS[r["series"]], excel_date(r["date"]))
        if key not in meetings:
            missing += 1
            continue
        mid, start = meetings[key]
        att_rows.append(f"  ({q(mid)}, {q(by_email[r['email']]['id'])}, {q(r['state'])}, 'import', "
                        f"{q((start + dt.timedelta(minutes=5)).isoformat())})")
    if missing:
        raise SystemExit(f"{missing} attendance rows did not match a meeting")
    out.append("-- Attendance (sandbox attendance, imported history)")
    out.append("insert into public.attendance (meeting_id, member_id, state, source, recorded_at) values")
    out.append(",\n".join(att_rows) + ";")
    out.append("")

    # ------------------------------------------------------------ hours (weekly totals)
    hours = read_xlsx(SANDBOX / "hours.xlsx")
    out.append("-- Hours (sandbox weekly totals)")
    out.append("insert into public.imported_week_hours (member_id, week_start, hours) values")
    out.append(",\n".join(
        f"  ({q(by_email[r['email']]['id'])}, {q(excel_date(r['week_start']).isoformat())}, {float(r['hours'])})"
        for r in hours) + ";")
    out.append("")

    # Invented: one approved exam-period pause for an Impact member.
    impact = [m for m in members if m["tier"] == "impact"]
    out.append("-- Invented: an approved exam-period pause")
    out.append("insert into public.pauses (member_id, starts_on, ends_on, reason, status, reviewed_by) values "
               f"({q(impact[1]['id'])}, '2026-10-05', '2026-10-11', 'Exam period', 'approved', {q(admins[0]['id'])});")
    out.append("")

    # ------------------------------------------------------------ onboarding (invented)
    manual = ["read_rules", "meet_buddy", "sign_contract", "org_email", "join_slack", "add_calendar"]
    ob_rows = []
    for m in members:
        steps = manual if m["email"] not in cohort else manual[: rnd.randint(1, 5)]
        joined_ts = dt.datetime.combine(m["joined"], dt.time(18, 0), tzinfo=dt.timezone.utc)
        for i, s in enumerate(steps):
            ob_rows.append(f"  ({q(m['id'])}, {q(s)}, {q((joined_ts + dt.timedelta(days=i)).isoformat())})")
    out.append("-- Invented: onboarding progress (the September cohort is part-way through)")
    out.append("insert into public.member_onboarding (member_id, step_key, completed_at) values")
    out.append(",\n".join(ob_rows) + ";")
    out.append("")

    # ------------------------------------------------------------ projects and tasks (invented)
    # TODO: replace with the ten official project names once the organisers share them.
    projects = [
        ("Summer School 2027", "summer-school", "#f59e0b",
         ["Book venue for Summer School", "Draft programme outline", "Shortlist speakers",
          "Open participant applications", "Budget v1", "Partner outreach list"]),
        ("Erasmus+ grant application", "grants", "#10b981",
         ["Read the 2027 call", "Collect partner letters", "Write impact section",
          "Budget table", "Internal review", "Submit application"]),
        ("Shape Talks #7", "shape-talks", "#8b5cf6",
         ["Pick the theme", "Invite three speakers", "Book Impact Hub event room",
          "Event page and registration", "Social posts", "Thank-you emails"]),
        ("Website relaunch", "shapers-tech", "#3b82f6",
         ["Content inventory", "New member profiles page", "Hosting and domain check",
          "Contact form", "Analytics setup", "Launch checklist"]),
        ("Shapers Voice podcast", "shapers-voice", "#ec4899",
         ["Episode list for season 1", "Record pilot episode", "Edit pilot",
          "Cover art", "Publish on Spotify", "Guest outreach"]),
        ("Impact Hub partnership", "community", "#14b8a6",
         ["Renew desk agreement", "Member access cards", "Joint event proposal", "Quarterly check-in"]),
        ("Member onboarding 2026", "community", "#6366f1",
         ["Onboarding meeting 1 deck", "Contracts for new members", "Assign buddies",
          "Accounts and emails", "Feedback survey"]),
        ("Community events Q4", "community", "#f97316",
         ["December social", "Volunteer day", "Book photographer", "Year-end recap post"]),
        ("Annual report 2026", "grants", "#64748b",
         ["Collect project numbers", "Write leader letter", "Design layout", "Send to board"]),
        ("Fundraising dinner", "grants", "#ef4444",
         ["Guest list", "Sponsor deck", "Venue and menu", "Invitations", "Auction items"]),
    ]
    statuses = ["done"] * 5 + ["doing"] * 2 + ["todo"] * 3
    priorities = ["low", "medium", "medium", "medium", "high", "high", "urgent"]
    proj_rows, pm_rows, task_rows = [], [], []
    for pname, series, color, titles in projects:
        pid = sid("project", pname)
        pool = [m for m in members if series == "community" or any(SERIES_IDS[s] == series for s in m["series"])]
        lead = next((m for m in pool if m["tier"] == "core"), None) or next((m for m in pool if m["tier"] == "impact"), pool[0])
        team = [lead] + rnd.sample([m for m in pool if m is not lead], k=min(4, len(pool) - 1))
        proj_rows.append(f"  ({q(pid)}, {q(pname)}, {q(color)}, {q(lead['id'])}, {q(lead['id'])}, "
                         f"{q('2026-09-07T08:00:00+00:00')})")
        pm_rows += [f"  ({q(pid)}, {q(m['id'])})" for m in team]
        for i, title in enumerate(titles):
            status = rnd.choice(statuses)
            assignee = rnd.choice(team) if rnd.random() > 0.1 else None
            created = dt.datetime(2026, 9, 14, 9, tzinfo=dt.timezone.utc) + dt.timedelta(days=rnd.randint(0, 30), hours=rnd.randint(0, 10))
            completed = None
            if status == "done":
                completed = min(created + dt.timedelta(days=rnd.randint(1, 14), hours=rnd.randint(0, 8)),
                                dt.datetime(2026, 10, 23, 16, tzinfo=dt.timezone.utc))
            due = (created + dt.timedelta(days=rnd.randint(7, 35))).date()
            if status != "done" and rnd.random() < 0.3:
                due = TODAY - dt.timedelta(days=rnd.randint(1, 6))  # a few overdue
            task_rows.append(
                f"  ({q(sid('task', pname, title))}, {q(pid)}, {q(title)}, {q(status)}, {q(rnd.choice(priorities))}, "
                f"{q(due.isoformat())}, {q(assignee['id'] if assignee else None)}, {q(lead['id'])}, "
                f"{q(created.isoformat())}, {q(completed.isoformat() if completed else None)}, {i})")
    out.append("-- Invented: projects and tasks (placeholders until the official project list arrives)")
    out.append("insert into public.projects (id, name, color, lead_id, created_by, created_at) values")
    out.append(",\n".join(proj_rows) + ";")
    out.append("insert into public.project_members (project_id, member_id) values")
    out.append(",\n".join(pm_rows) + "\non conflict do nothing;")
    out.append("insert into public.tasks (id, project_id, title, status, priority, due_on, assignee_id, created_by, "
               "created_at, completed_at, sort_order) values")
    out.append(",\n".join(task_rows) + ";")
    out.append("")
    out.append("commit;")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(members)} members, {len(meetings)} meetings, "
          f"{len(att_rows)} attendance rows, {len(hours)} hour rows, {len(projects)} projects, {len(task_rows)} tasks")


if __name__ == "__main__":
    main()
